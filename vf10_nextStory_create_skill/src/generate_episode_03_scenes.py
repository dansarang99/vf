def build_scenes():
    scenes = []
    curr_time = 0.0
    for sid, char, text, dur in SCENES_DATA:
        entry = {
            "scene_id": sid,
            "character": char,
            "text": text,
            "dialogue": text,
            "start": round(curr_time, 2),
            "end": round(curr_time + dur, 2),
            "duration": dur
        }
        scenes.append(entry)
        curr_time += dur

    out_file = os.path.join(RESULT_DIR, "[101]_episode_03_europa_scenes.json")
    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(scenes, f, ensure_ascii=False, indent=2)

    print(f"[*] 에피소드 03 총 {len(scenes)}개 씬 메타데이터 생성 완료 -> {out_file}")
    return out_file

if __name__ == "__main__":
    build_scenes()
