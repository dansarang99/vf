# 씬 타임라인 구성 및 마스터 대본 생성
scenes = []
current_time = 0.0

for idx, (character, text, duration) in enumerate(RAW_SCENES, start=1):
    # 발화 간격 대기시간(gap): 긴장감 넘치는 빠른 전개 0.8s ~ 1.5s
    gap = 1.0 if idx > 1 else 2.0
    start_time = round(current_time + gap, 2)
    end_time = round(start_time + duration, 2)
    current_time = end_time

    scenes.append({
        "scene_id": idx,
        "character": character,
        "text": text,
        "start": start_time,
        "end": end_time,
        "duration": duration,
        "gap": gap
    })

total_duration = scenes[-1]["end"]
print(f"[INFO] 씬 타임라인 연산 완료: 총 {len(scenes)}씬, 총 상영시간 {total_duration}초 ({round(total_duration/60, 2)}분)")

